def evaluate_neurodivergent_sensors(decibels: float, crowd_density: float, motion_jerk: float, lux: float):
    """Computes sensory stress indexes for neurodivergent sensory processing triggers."""
    noise_factor = max(0.0, (decibels - 65.0) / 35.0)
    crowd_factor = crowd_density
    motion_factor = min(1.0, motion_jerk / 10.0)
    light_factor = 1.0 if lux > 8000 or lux < 20 else 0.0

    score = (
        (noise_factor * 0.35) +
        (crowd_factor * 0.30) +
        (motion_factor * 0.20) +
        (light_factor * 0.15)
    )
    score = round(min(1.0, max(0.0, score)), 2)
    is_overloaded = score > 0.65

    reason = "Environment is balanced and low-stimulation."
    if is_overloaded:
        if noise_factor > 0.5:
            reason = "High ambient decibel spike detected. Potential auditory overload."
        elif crowd_factor > 0.6:
            reason = "Dense crowd congestion detected. High visual/spatial stimulation."
        elif motion_factor > 0.5:
            reason = "Erratic movement vectors detected."
        else:
            reason = "Harsh environmental lighting conditions recorded."

    return is_overloaded, score, reason


