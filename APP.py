def extract_price_info(category: str, tags: dict, default_estimate: float) -> tuple:
    charge_tag = tags.get("charge") or tags.get("cost")
    if charge_tag:
        return charge_tag, True

    if category == "🚻 Restrooms":
        fee_tag = tags.get("fee")
        if fee_tag == "no":
            return "Free", True
        if fee_tag == "yes":
            return "Fee charged (amount not listed)", True
        return (f"₹{default_estimate:.0f} (assumed)" if default_estimate > 0 else "Likely free (assumed)"), False

    if category == "🏨 Hotels":
        stars = tags.get("stars")
        if stars:
            multiplier = {"1": 0.6, "2": 0.8, "3": 1.0, "4": 1.6, "5": 2.5}.get(str(stars), 1.0)
            return f"₹{default_estimate * multiplier:.0f}/night (assumed, {stars}★)", False
        return f"₹{default_estimate:.0f}/night (assumed)", False

    price_range = tags.get("price_range")
    if price_range:
        return f"{price_range} (venue-reported range)", True
    return f"₹{default_estimate:.0f}/meal (assumed)", False


