def safe_json(resp: requests.Response, label: str) -> dict:
    """Parses a response as JSON, raising a clear error instead of a
    raw JSONDecodeError if the service returned something else (an
    HTML error page, empty body, rate-limit message, etc.)."""
    try:
        return resp.json()
    except Exception:
        raise RuntimeError(
            f"{label} returned a non-JSON response (HTTP {resp.status_code}): "
            f"{resp.text[:200]!r}"
        )


def _geocode_nominatim(place: str):
    params = {"q": place, "format": "json", "limit": 1}
    resp = _session.get(NOMINATIM_URL, params=params, headers=REQUEST_HEADERS, timeout=15)
    if resp.status_code == 429:
        raise RuntimeError("rate limited (HTTP 429)")
    if resp.status_code != 200:
        raise RuntimeError(f"HTTP {resp.status_code}")
    results = safe_json(resp, "Nominatim")
    if not results:
        return None
    top = results[0]
    return float(top["lat"]), float(top["lon"]), top.get("display_name", place)


def _geocode_photon(place: str):
    """Fallback geocoder (Komoot's Photon, built on the same OSM data as
    Nominatim) -- used when Nominatim itself is unavailable, since
    Nominatim's public instance shares rate limits across every app on a
    given IP, and Streamlit Cloud's shared outbound IPs can get caught by
    other unrelated apps' traffic, not just this one's."""
    params = {"q": place, "limit": 1}
    resp = _session.get(PHOTON_URL, params=params, headers=REQUEST_HEADERS, timeout=15)
    if resp.status_code != 200:
        raise RuntimeError(f"HTTP {resp.status_code}")
    data = safe_json(resp, "Photon")
    features = data.get("features", [])
    if not features:
        return None
    feat = features[0]
    lng, lat = feat["geometry"]["coordinates"]
    props = feat.get("properties", {})
    name = ", ".join(filter(None, [props.get("name"), props.get("city"), props.get("country")]))
    return float(lat), float(lng), name or place


@st.cache_data(ttl=3600, show_spinner=False)
def geocode(place: str):
    """Free, keyless geocoding. Tries OpenStreetMap's Nominatim first
    (with retry-with-backoff on rate limiting), then falls back to
    Photon -- a second, independently-hosted geocoder over the same OSM
    data -- if Nominatim is unavailable. Returns (lat, lng, display_name).
    Raises RuntimeError if neither service can find the place. Results
    are cached for an hour so repeat lookups don't re-hit either API."""
    last_error = None
    for delay in (0, 2, 5):
        if delay:
            time.sleep(delay)
        try:
            result = _geocode_nominatim(place)
            if result:
                return result
            raise RuntimeError(f"Couldn't geocode '{place}' -- try a more specific name.")
        except RuntimeError as e:
            if "rate limited" not in str(e):
                raise
            last_error = str(e)
            continue

    try:
        result = _geocode_photon(place)
        if result:
            return result
    except Exception as e:
        last_error = f"{last_error}; Photon fallback also failed: {e}"

    raise RuntimeError(
        f"Geocoding is temporarily unavailable for '{place}' ({last_error}). "
        "Wait a bit and try again."
    )


