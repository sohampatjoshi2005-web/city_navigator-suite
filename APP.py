def haversine_km(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    R = 6371.0
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lng2 - lng1)
    a = math.sin(dphi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlambda / 2) ** 2
    return 2 * R * math.asin(math.sqrt(a))


# --- Real GPS support -------------------------------------------------------
# A live device fix arrives as raw "lat,lng" (see render_live_gps_locator()
# below), which is NOT a place name -- it must skip the geocoding chain
# entirely (Nominatim/Geoapify/Photon all expect free text) and be used
# directly as coordinates. Reverse geocoding is only for a human-readable
# label to show the user; routing itself always uses the raw fix.
_COORD_RE = re.compile(r"^\s*(-?\d{1,3}(?:\.\d+)?)\s*,\s*(-?\d{1,3}(?:\.\d+)?)\s*$")
NOMINATIM_REVERSE_URL = "https://nominatim.openstreetmap.org/reverse"


def parse_coord_string(text: str) -> Optional[tuple]:
    """Recognizes a raw 'lat,lng' string (what a live GPS fix looks like)
    and returns (lat, lng), or None if the text is an ordinary place name."""
    match = _COORD_RE.match(text)
    if not match:
        return None
    lat, lng = float(match.group(1)), float(match.group(2))
    if -90.0 <= lat <= 90.0 and -180.0 <= lng <= 180.0:
        return lat, lng
    return None


@st.cache_data(ttl=3600, show_spinner=False)
def reverse_geocode(lat: float, lng: float) -> tuple:
    """Best-effort human-readable label + country for a raw lat/lng (e.g. a
    live GPS fix). Falls back to the raw coordinates as the label if
    Nominatim can't resolve them (offline, rate-limited, middle of nowhere)."""
    try:
        resp = _throttled_nominatim_get({
            "lat": lat, "lon": lng, "format": "json", "zoom": 16, "addressdetails": 1,
        })
        data = safe_json(resp, "Nominatim reverse geocoding")
        label = data.get("display_name")
        country = data.get("address", {}).get("country")
        if label:
            return label, country
    except Exception:
        pass
    return f"{lat:.5f}, {lng:.5f}", None


