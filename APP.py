def directions_speech_text(route: RouteResult, destination: str, max_steps: int = 8) -> str:
    dist_km = route.distance_m / 1000.0
    dur_min = route.duration_s / 60.0
    parts = [
        f"{destination} is {dist_km:.1f} kilometers away, about {dur_min:.0f} minutes."
    ]
    steps = route.steps[:max_steps]
    for i, step in enumerate(steps, start=1):
        parts.append(f"Step {i}: {step['instruction']}, for {_format_step_distance(step['distance_m'])}.")
    if len(route.steps) > max_steps:
        parts.append(f"Plus {len(route.steps) - max_steps} more steps -- see the screen for the full list.")
    return " ".join(parts)


