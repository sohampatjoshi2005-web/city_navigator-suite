# ============================================================
# Tab 2 helpers: Sensory & Neurodivergent-Friendly baseline heuristic
# ============================================================
#
# Design note: this is explicitly a SIMULATED HEURISTIC, not live sensor
# data -- there is no free, structured, global data source for noise
# levels, lighting, or crowd density (that's precisely the gap being
# illustrated). To keep the simulation honest rather than arbitrary:
#   1. It's DETERMINISTIC per place (seeded from the place name), so the
#      same place always gets the same baseline -- not fresh random
#      numbers on every click, which would look obviously fake.
#   2. The baseline is nudged by the place's actual OSM category (a
#      library or place of worship defaults quieter than a bar or
#      market), so it's grounded in one real signal, not pure noise.
#   3. It is layered UNDER a real, session-based crowdsourced reports
#      system (same aggregation pattern as a Google Maps-style
#      accessibility layer) -- once even one real report exists for a
#      place, that takes precedence over the simulated baseline, and the
#      UI makes that distinction explicit rather than blending them
#      silently.

import hashlib

SENSORY_QUIET_CATEGORIES = {
    "library", "place_of_worship", "monastery", "hospital", "clinic",
}
SENSORY_LOUD_CATEGORIES = {
    "bar", "pub", "nightclub", "marketplace", "fast_food", "stadium",
}

SENSORY_FIELDS = {
    "noise_level": {"label": "Typical noise level", "options": ["Quiet", "Moderate", "Loud"]},
    "lighting": {"label": "Typical lighting", "options": ["Dim", "Moderate", "Bright/harsh"]},
    "crowd_density": {"label": "Typical crowd density", "options": ["Sparse", "Moderate", "Crowded"]},
    "quiet_hours": {"label": "Known quiet hours (if any)", "options": ["None known", "Early morning", "Late evening", "Varies by day"]},
}


def fetch_osm_category(place_name: str, lat: float, lng: float, radius_m: int = 300) -> Optional[str]:
    """Looks up the nearest matching OSM node's amenity/shop/leisure tag,
    to ground the simulated sensory baseline in one real signal instead
    of pure randomness."""
    overpass_ql = (
        f'[out:json][timeout:15];'
        f'node["name"~"{place_name}",i](around:{radius_m},{lat},{lng});'
        f"out center 3;"
    )
    try:
        resp = _session.post(OVERPASS_URL, data={"data": overpass_ql},
                              headers=REQUEST_HEADERS, timeout=20)
        data = safe_json(resp, "Overpass")
    except Exception:
        return None
    for el in data.get("elements", []):
        tags = el.get("tags", {})
        for key in ("amenity", "shop", "leisure", "tourism"):
            if key in tags:
                return tags[key]
    return None


def simulate_sensory_baseline(place_name: str, osm_category: Optional[str]) -> dict:
    """Deterministic, seeded-by-name simulated baseline (see design note
    above). NOT live data -- clearly labeled as such in the UI."""
    seed_int = int(hashlib.sha256(place_name.strip().lower().encode()).hexdigest(), 16) % (2**32)
    rng = random.Random(seed_int)

    if osm_category in SENSORY_QUIET_CATEGORIES:
        noise_bias, light_bias, crowd_bias = -1, -1, -1
    elif osm_category in SENSORY_LOUD_CATEGORIES:
        noise_bias, light_bias, crowd_bias = 1, 1, 1
    else:
        noise_bias = light_bias = crowd_bias = 0

    def _pick(options, bias):
        idx = 1 + bias + rng.choice([-1, 0, 0, 1])  # center-weighted jitter around the bias
        idx = max(0, min(len(options) - 1, idx))
        return options[idx]

    return {
        "noise_level": _pick(SENSORY_FIELDS["noise_level"]["options"], noise_bias),
        "lighting": _pick(SENSORY_FIELDS["lighting"]["options"], light_bias),
        "crowd_density": _pick(SENSORY_FIELDS["crowd_density"]["options"], crowd_bias),
        "quiet_hours": rng.choice(SENSORY_FIELDS["quiet_hours"]["options"]),
        "source": "simulated",
        "osm_category_used": osm_category,
    }


def aggregate_sensory_reports(reports: list, field_key: str) -> dict:
    """Majority-vote one field across all real crowdsourced reports for a
    place -- same pattern as an accessibility-style aggregation, applied
    to sensory fields instead."""
    answers = [r[field_key] for r in reports if r.get(field_key)]
    if not answers:
        return {"answer": None, "count": 0, "total": 0}
    tally = {}
    for a in answers:
        tally[a] = tally.get(a, 0) + 1
    best = max(tally.items(), key=lambda kv: kv[1])
    return {"answer": best[0], "count": best[1], "total": len(answers)}


SENSORY_GAP_STATEMENT = (
    "**Gap addressed -- Sensory & Neurodivergent-Friendly Info:** mainstream maps "
    "have essentially no structured data on noise levels, lighting, crowd density, "
    "or quiet hours -- information that materially affects whether a place is "
    "usable for someone who is sound- or light-sensitive, autistic, has ADHD, or "
    "experiences sensory overload. This tab shows a transparently-labeled simulated "
    "baseline (seeded per place, nudged by the place's real OSM category -- not "
    "arbitrary) layered under a real, session-based crowdsourced reporting system "
    "that takes precedence once actual reports exist, the same way a real product "
    "would bootstrap a brand-new data category with heuristics before user reports "
    "accumulate."
)


