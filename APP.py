JSONLD_FETCH_TIMEOUT_S = 12

_JSONLD_SCRIPT_RE = re.compile(
    r'<script[^>]+type=["\']application/ld\+json["\'][^>]*>(.*?)</script>',
    re.IGNORECASE | re.DOTALL,
)

_DIGITS_RE = re.compile(r"\d+")
_HOURS_TIME_RE = re.compile(r"(\d{1,2}):(\d{2})")

REQUEST_HEADERS = {
    "User-Agent": "CityNavigatorSuite/1.0 (contact: local-app; +https://streamlit.io)"
}

OVERPASS_URL = "https://overpass-api.de/api/interpreter"
NOMINATIM_URL = "https://nominatim.openstreetmap.org/search"
ANTHROPIC_MESSAGES_URL = "https://api.anthropic.com/v1/messages"
DEFAULT_VLM_MODEL = "claude-sonnet-4-6"

# A single shared requests.Session -- reuses connections across calls
# instead of opening a fresh TCP/TLS handshake per request.
_session = requests.Session()


def get_anthropic_key() -> Optional[str]:
    """Reads the Anthropic API key from Streamlit secrets first (the
    normal way to store it on Streamlit Cloud), falling back to an
    environment variable for local/Colab runs."""
    try:
        if "ANTHROPIC_API_KEY" in st.secrets:
            return st.secrets["ANTHROPIC_API_KEY"]
    except Exception:
        # st.secrets raises if no secrets.toml exists at all -- that's
        # fine, just fall through to the env var.
        pass
    return os.environ.get("ANTHROPIC_API_KEY")


def safe_json(resp: requests.Response, label: str) -> dict:
    """Parses a response as JSON, raising a clear error instead of a
    raw JSONDecodeError if the service returned something else (an
    HTML error page, empty body, rate-limit message, etc.)."""
    try:
        return resp.json()
    except Exception:
        raise RuntimeError(
            f"{label} returned a non-JSON response (HTTP {resp.status_code}): "
            f"{resp.text[:200]!r}"
        )


@st.cache_data(ttl=3600, show_spinner=False)
def geocode(place: str):
    """Free, keyless geocoding via OpenStreetMap's Nominatim. Returns
    (lat, lng, display_name). Raises RuntimeError if the place can't
    be found.

    Nominatim enforces a strict ~1 request/second per IP and returns
    HTTP 429 if that's exceeded -- easy to hit on shared hosting like
    Streamlit Cloud where many apps/users can share an IP. Retries with
    backoff on 429, and results are cached for an hour so repeat lookups
    of the same place don't re-hit the API at all."""
    params = {"q": place, "format": "json", "limit": 1}
    last_error = None
    for attempt, delay in enumerate((0, 2, 5)):
        if delay:
            time.sleep(delay)
        try:
            resp = _session.get(
                NOMINATIM_URL, params=params, headers=REQUEST_HEADERS, timeout=15
            )
        except Exception as e:
            last_error = str(e)
            continue

        if resp.status_code == 429:
            last_error = "rate limited (HTTP 429)"
            continue
        if resp.status_code != 200:
            raise RuntimeError(f"Geocoding failed for '{place}' (HTTP {resp.status_code})")

        results = safe_json(resp, "Nominatim")
        if not results:
            raise RuntimeError(f"Couldn't geocode '{place}' -- try a more specific name.")
        top = results[0]
        return float(top["lat"]), float(top["lon"]), top.get("display_name", place)

    raise RuntimeError(
        f"Geocoding service is rate-limiting requests right now ({last_error}). "
        "Wait a few seconds and try again."
    )


