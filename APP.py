def render_live_gps_locator():
    """One-tap 'use my real location' control. Uses the browser's actual
    Geolocation API (device GPS / Wi-Fi positioning, not a simulation) to
    get a real fix, then pre-fills Origin on every routing tab (1, 2, 4, 5)
    with it as a raw 'lat,lng' string -- geocode() special-cases that format
    (see parse_coord_string()) so routing uses the exact fix, not a
    geocoded guess.

    This is a single on-demand fix (getCurrentPosition), not continuous
    live tracking (watchPosition) -- Streamlit reruns the whole script per
    interaction, so continuous tracking would mean a background refresh
    loop; a one-tap "get my current position, use it, tap again to
    refresh" model fits that execution model far more cleanly and is what
    turn-by-turn nav really needs at the start of a trip anyway.

    Implementation note: there's no native Streamlit widget for browser
    geolocation (unlike st.camera_input/st.audio_input for camera/mic), so
    this uses the same components.html + URL query-param handoff the app's
    earlier voice-command prototype used: JS gets the fix, then navigates
    the top-level page to the same URL with gps_lat/gps_lng/gps_acc query
    params attached, causing one rerun in which Python reads them back out
    via st.query_params."""
    st.subheader("📍 Live GPS")
    st.caption(
        "Uses your **actual device location** (browser Geolocation API -- GPS/Wi-Fi "
        "positioning, not a simulation) to fill in Origin below on the Greenest Route, "
        "Ghost Jam, Offline Navigator, and Sensory & Safety tabs. One fix per tap, not "
        "continuous tracking -- tap again any time to refresh it. Nothing is stored "
        "server-side beyond the current page load."
    )

    components.html(
        """
        <div style="font-family: sans-serif;">
          <button id="gpsBtn" style="padding:8px 16px; font-size:15px; cursor:pointer;">
            📍 Use my current location
          </button>
          <p id="gpsOutput" style="margin-top:8px;">Tap to share your live GPS location as the origin.</p>
        </div>
        <script>
        (function() {
          const btn = document.getElementById('gpsBtn');
          const output = document.getElementById('gpsOutput');
          if (!('geolocation' in navigator)) {
            output.innerText = 'Geolocation is not supported in this browser.';
            btn.disabled = true;
            return;
          }
          btn.onclick = function() {
            output.innerText = 'Requesting location permission...';
            navigator.geolocation.getCurrentPosition(
              function(pos) {
                const lat = pos.coords.latitude;
                const lng = pos.coords.longitude;
                const acc = pos.coords.accuracy;
                output.innerText = 'Got fix: ' + lat.toFixed(5) + ', ' + lng.toFixed(5) +
                  ' (\u00b1' + Math.round(acc) + 'm) -- updating origin...';
                const url = new URL(window.top.location.href);
                url.searchParams.set('gps_lat', lat.toFixed(6));
                url.searchParams.set('gps_lng', lng.toFixed(6));
                url.searchParams.set('gps_acc', Math.round(acc));
                url.searchParams.set('t', Date.now());
                window.top.location.href = url.toString();
              },
              function(err) {
                output.innerText = 'Location error: ' + err.message +
                  ' -- check your browser/OS location permissions.';
              },
              {enableHighAccuracy: true, timeout: 12000, maximumAge: 0}
            );
          };
        })();
        </script>
        """,
        height=90,
    )

    if "gps_last_fix_id" not in st.session_state:
        st.session_state.gps_last_fix_id = None

    gps_lat_str = st.query_params.get("gps_lat")
    gps_lng_str = st.query_params.get("gps_lng")
    gps_acc_str = st.query_params.get("gps_acc")
    fix_id = f"{gps_lat_str}:{gps_lng_str}:{st.query_params.get('t')}"

    if gps_lat_str and gps_lng_str and fix_id != st.session_state.gps_last_fix_id:
        st.session_state.gps_last_fix_id = fix_id
        try:
            lat, lng = float(gps_lat_str), float(gps_lng_str)
            coord_str = f"{lat:.6f},{lng:.6f}"
            with st.spinner("Resolving your location to an address..."):
                label, _country = reverse_geocode(lat, lng)
            # Set session_state directly for each origin widget's key --
            # since this runs before those st.text_input(...) calls later
            # in the script, Streamlit picks up this value as the widget's
            # current value on this rerun (the standard "set state before
            # the widget is created" pattern; doing this *after* the widget
            # exists in the same run would raise instead).
            for key in ("t1_origin", "t2_origin", "t4_origin", "t5_origin"):
                st.session_state[key] = coord_str
            st.session_state["gps_label"] = label
            st.session_state["gps_accuracy_m"] = gps_acc_str
        except ValueError:
            pass

    if st.session_state.get("gps_label"):
        acc_note = f" (\u00b1{st.session_state['gps_accuracy_m']}m)" if st.session_state.get("gps_accuracy_m") else ""
        st.success(
            f"📍 Live origin set: {st.session_state['gps_label']}{acc_note} -- applied to "
            f"Origin on the Greenest Route, Ghost Jam, Offline Navigator, and Sensory & Safety tabs."
        )


