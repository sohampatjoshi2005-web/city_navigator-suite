# --- Listing Data Trust / Freshness Audit -----------------------------------
# Source A: the business's own website (schema.org JSON-LD structured data,
# what most modern sites already embed for SEO). Source B: an independent
# OpenStreetMap record via the same Overpass setup used by
# fetch_nearby_amenities() above. Comparing two independent sources -- rather
# than trusting either one, or a single crowdsourced edit, at face value --
# is what turns "an editor said so" into an actual confidence score.
JSONLD_FETCH_TIMEOUT_S = 12
_JSONLD_SCRIPT_RE = re.compile(
    r'<script[^>]+type=["\']application/ld\+json["\'][^>]*>(.*?)</script>',
    re.IGNORECASE | re.DOTALL,
)
_DIGITS_RE = re.compile(r"\d+")
_HOURS_TIME_RE = re.compile(r"(\d{1,2}):(\d{2})")


def _find_local_business_node(parsed) -> Optional[dict]:
    """JSON-LD can be a single object, a list, or wrapped in @graph -- dig
    through all three shapes looking for a LocalBusiness-ish node (any
    @type containing 'Business', 'Restaurant', 'Store', etc., since
    schema.org has dozens of specific subtypes)."""
    candidates = []
    if isinstance(parsed, list):
        candidates = parsed
    elif isinstance(parsed, dict):
        if "@graph" in parsed and isinstance(parsed["@graph"], list):
            candidates = parsed["@graph"]
        else:
            candidates = [parsed]

    for node in candidates:
        if not isinstance(node, dict):
            continue
        node_type = node.get("@type", "")
        type_str = " ".join(node_type) if isinstance(node_type, list) else str(node_type)
        if any(kw in type_str for kw in (
            "Business", "Restaurant", "Store", "Organization", "Cafe", "Hotel",
            "University", "College", "School", "GovernmentOffice", "Museum",
            "Library", "Hospital", "Bank",
        )):
            return node
    return None


def fetch_website_listing(url: str) -> Optional[dict]:
    """Fetches a business's own website and extracts schema.org JSON-LD
    structured data (name, phone, address, opening hours) -- Source A: the
    business's own stated info, no API key or billing needed, works for
    businesses anywhere as long as the site has SEO structured data, which
    most modern business sites do."""
    if not re.match(r"^https?://", url, re.IGNORECASE):
        url = "https://" + url

    try:
        resp = _session.get(url, headers=REQUEST_HEADERS, timeout=JSONLD_FETCH_TIMEOUT_S)
    except Exception as e:
        raise RuntimeError(f"Couldn't reach {url}: {e}")

    if resp.status_code != 200:
        raise RuntimeError(f"{url} returned HTTP {resp.status_code}")

    matches = _JSONLD_SCRIPT_RE.findall(resp.text)
    for raw in matches:
        try:
            parsed = json.loads(_html_module.unescape(raw.strip()))
        except Exception:
            continue
        node = _find_local_business_node(parsed)
        if node:
            addr = node.get("address")
            if isinstance(addr, dict):
                addr_str = ", ".join(filter(None, [
                    addr.get("streetAddress"), addr.get("addressLocality"),
                    addr.get("addressRegion"), addr.get("postalCode"),
                ]))
            else:
                addr_str = addr if isinstance(addr, str) else None

            hours = node.get("openingHours") or node.get("openingHoursSpecification")
            if isinstance(hours, list):
                hours = "; ".join(str(h) for h in hours)

            return {
                "name": node.get("name"),
                "phone": node.get("telephone"),
                "address": addr_str,
                "opening_hours": hours,
            }
    return None


def fetch_osm_listing(business_name: str, lat: float, lng: float, radius_m: int = 3000) -> Optional[dict]:
    """Looks up the same business in OpenStreetMap (via Overpass) as Source
    B -- a second, independent, free/keyless source alongside the
    business's own site.

    Searches nodes, ways, AND relations -- not just nodes. Many real
    businesses (dealerships, campuses, hotels, malls) are mapped in OSM as
    a way (a building footprint) or relation, not a point node, so a
    node-only search silently misses them even when OSM has good data for
    that business."""
    safe_name = business_name.replace("\\", "\\\\").replace('"', '\\"')
    overpass_ql = (
        f'[out:json][timeout:20];'
        f'nwr["name"~"{safe_name}",i](around:{radius_m},{lat},{lng});'
        f"out center 10 tags;"
    )
    try:
        resp = _session.post(OVERPASS_URL, data={"data": overpass_ql},
                              headers=REQUEST_HEADERS, timeout=25)
        data = safe_json(resp, "Overpass")
    except Exception:
        return None

    elements = data.get("elements", [])
    if not elements:
        return None

    # Multiple results are common now that we search all element types --
    # pick the one with the most useful tags filled in, not just the first
    # one returned, since Overpass doesn't rank by data completeness.
    def _completeness(el):
        t = el.get("tags", {})
        return sum(1 for k in ("phone", "contact:phone", "opening_hours", "addr:street") if t.get(k))

    best = max(elements, key=_completeness)
    tags = best.get("tags", {})
    osm_lat = best.get("lat") or (best.get("center") or {}).get("lat")
    osm_lng = best.get("lon") or (best.get("center") or {}).get("lon")
    return {
        "name": tags.get("name"),
        "phone": tags.get("phone") or tags.get("contact:phone"),
        "opening_hours": tags.get("opening_hours"),
        "address": ", ".join(filter(None, [
            tags.get("addr:housenumber"), tags.get("addr:street"), tags.get("addr:city"),
        ])) or None,
        "lat": osm_lat,
        "lng": osm_lng,
    }


def _fuzzy_match(a: Optional[str], b: Optional[str]) -> float:
    """0..1 similarity between two strings, tolerant of formatting
    differences (e.g. phone number punctuation, minor address wording)."""
    if not a or not b:
        return 0.0
    return difflib.SequenceMatcher(None, a.lower().strip(), b.lower().strip()).ratio()


def _phones_match(a: Optional[str], b: Optional[str]) -> bool:
    """Phone comparison by digits only, handling three common formatting
    differences that generic string similarity gets wrong:
      1. Punctuation/spacing (+91-674-1234567 vs 91 674 1234567)
      2. Country code present vs. absent (91674... vs 674...)
      3. India's domestic trunk prefix '0' vs. country code '91'
         (0674-1234567 vs +91-674-1234567 -- the SAME number, but a
         leading 0 replaces where +91 would go, which plain digit
         suffix-matching doesn't handle)."""
    if not a or not b:
        return False
    da, db = "".join(_DIGITS_RE.findall(a)), "".join(_DIGITS_RE.findall(b))
    if not da or not db:
        return False
    da_norm = da[1:] if da.startswith("0") else da
    db_norm = db[1:] if db.startswith("0") else db
    shorter, longer = (da_norm, db_norm) if len(da_norm) <= len(db_norm) else (db_norm, da_norm)
    return longer.endswith(shorter) and len(shorter) >= 7


def _hours_match(a: Optional[str], b: Optional[str]) -> bool:
    """Hours comparison by extracted HH:MM tokens, not raw string
    similarity -- generic fuzzy matching scores 'Mo-Sa 09:00-21:00' as
    near-identical to 'Mo-Sa 10:00-20:00' because they share most
    characters, which would silently hide a real mismatch. This instead
    requires the actual time tokens to match."""
    if not a or not b:
        return False
    times_a = _HOURS_TIME_RE.findall(a)
    times_b = _HOURS_TIME_RE.findall(b)
    if not times_a or not times_b:
        return _fuzzy_match(a, b) >= 0.8  # no parseable times -- fall back, but stricter
    return set(times_a) == set(times_b)


def compare_listings(website: Optional[dict], osm: Optional[dict]) -> dict:
    """Field-by-field comparison producing a status + confidence per field,
    plus an overall trust score. Source A is the business's own website
    (JSON-LD), Source B is OpenStreetMap -- source-agnostic in structure,
    so swapping in Google Places or Yelp later needs no change here, as
    long as the caller passes the same {name, phone, address,
    opening_hours} shape."""
    fields = {}

    def _field_fuzzy(label, a, b, threshold=0.6):
        if not a and not b:
            return {"label": label, "status": "no_data", "website": a, "osm": b}
        if not a or not b:
            return {"label": label, "status": "unverifiable", "website": a, "osm": b}
        score = _fuzzy_match(str(a), str(b))
        status = "match" if score >= threshold else "mismatch"
        return {"label": label, "status": status, "website": a, "osm": b, "similarity": round(score, 2)}

    def _field_exact(label, a, b, matcher):
        if not a and not b:
            return {"label": label, "status": "no_data", "website": a, "osm": b}
        if not a or not b:
            return {"label": label, "status": "unverifiable", "website": a, "osm": b}
        status = "match" if matcher(str(a), str(b)) else "mismatch"
        return {"label": label, "status": status, "website": a, "osm": b}

    w = website or {}
    o = osm or {}
    fields["phone"] = _field_exact("Phone", w.get("phone"), o.get("phone"), _phones_match)
    fields["address"] = _field_fuzzy("Address", w.get("address"), o.get("address"), threshold=0.5)
    fields["hours"] = _field_exact("Opening hours", w.get("opening_hours"), o.get("opening_hours"), _hours_match)

    # Only fields where BOTH sources had data to compare count toward the
    # trust score -- "unverifiable" (one source missing that field) and
    # "no_data" (neither had it) aren't evidence of a mismatch, so scoring
    # them as failures would misleadingly tank the score for businesses
    # that just have thin data on one side, rather than actual conflicts.
    n_checked = sum(1 for f in fields.values() if f["status"] in ("match", "mismatch", "ok"))
    n_ok = sum(1 for f in fields.values() if f["status"] in ("match", "ok"))
    trust_score = round(100 * n_ok / n_checked) if n_checked else None

    return {"fields": fields, "trust_score": trust_score}


