            random.seed(7)
            noise_points = [
                {"lat": lat, "lng": lng, "weight": random.uniform(0.15, 1.0)}
                for lat, lng in sampled5
            ]
            avg_noise = sum(p["weight"] for p in noise_points) / len(noise_points)
            quiet_score = round(100 * (1 - avg_noise))

            def _darkness_factor(hour: int) -> float:
                diff = min(abs(hour - 2), 24 - abs(hour - 2))
                return max(0.2, 1.0 - diff / 12)

            darkness = _darkness_factor(hour5)
