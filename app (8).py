def _tokenize(text: str) -> set:
    return set(re.findall(r"[a-z0-9]+", text.lower()))


def fragmented_local_semantic_search(query: str, lat: float, lng: float, radius_m: int = 1200, top_k: int = 10) -> list:
    """Best-effort local search across three fragmented, differently-shaped
    data sources this app already talks to (OSM points, Wikipedia articles,
    session community notes), ranked by simple token-overlap scoring rather
    than true embeddings (keeps this dependency-free)."""
    q_tokens = _tokenize(query)
    if not q_tokens:
        return []

    candidates = []
    for poi in fetch_named_points_of_interest(lat, lng, radius_m):
        candidates.append({"source": "🗺️ OSM", "name": poi["name"], "text": poi["text"], "lat": poi["lat"], "lng": poi["lng"]})

    for hit in wiki_geosearch(lat, lng, radius_m):
        candidates.append({"source": "📖 Wikipedia", "name": hit.get("title", ""), "text": hit.get("title", ""), "lat": hit.get("lat"), "lng": hit.get("lon")})

    for note in st.session_state.get("community_notes", []):
        if haversine_km(lat, lng, note["lat"], note["lng"]) * 1000 <= radius_m:
            candidates.append({"source": "📌 Community note", "name": note["name"], "text": f"{note['category']} {note['name']}", "lat": note["lat"], "lng": note["lng"]})

    scored = []
    for c in candidates:
        c_tokens = _tokenize(f"{c['name']} {c['text']}")
        overlap = len(q_tokens & c_tokens)
        if overlap > 0:
            scored.append((overlap, c))
    scored.sort(key=lambda pair: pair[0], reverse=True)
    return [c for _, c in scored[:top_k]]


# --- Weather & Calamity Detection -------------------------------------------
CALAMITY_SEVERE_TYPES = {"ice_risk", "extreme_heat"}


def classify_route_calamity_risk(weather_hazards: List[dict]) -> dict:
    """Aggregates the route's already-sampled weather hazard points (see
    sample_weather_hazards_along_route) into one overall advisory level for
    the whole trip, rather than just per-point flags."""
    if not weather_hazards:
        return {"level": "🟢 Normal", "summary": "No adverse weather detected along the sampled route points."}
    n_total = len(weather_hazards)
    n_severe = sum(1 for h in weather_hazards if h["type"] in CALAMITY_SEVERE_TYPES)
    if n_severe >= 2 or n_total >= 5:
        level = "🔴 Warning"
    elif n_total >= 2 or n_severe >= 1:
        level = "🟠 Watch"
    else:
        level = "🟡 Advisory"
    notes = sorted({h["note"] for h in weather_hazards})
    return {"level": level, "summary": f"{n_total} hazardous sample point(s) along the route: " + "; ".join(notes)}


