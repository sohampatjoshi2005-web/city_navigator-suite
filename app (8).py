def classify_collision_risk(area_frac: float, center_offset_frac: float) -> int:
    if area_frac > _RISK_AREA_HIGH and center_offset_frac < _RISK_CENTER_TIGHT:
        return 3
    if area_frac > _RISK_AREA_MED and center_offset_frac < _RISK_CENTER_LOOSE:
        return 2
    if area_frac > _RISK_AREA_LOW:
        return 1
    return 0


def run_collision_detection(image: Image.Image):
    model = load_yolo_model()
    if model is None:
        return None, [], None

    try:
        img_w, img_h = image.size
        results = model.predict(image, verbose=False)[0]
        names = results.names

        annotated = image.convert("RGB").copy()
        draw = ImageDraw.Draw(annotated)
        detections = []
        overall_level = 0

        for box in results.boxes:
            cls_name = names.get(int(box.cls[0]), "object")
            if cls_name not in COLLISION_RELEVANT_CLASSES:
                continue
            conf = float(box.conf[0])
            x1, y1, x2, y2 = [float(v) for v in box.xyxy[0]]
            area_frac = ((x2 - x1) * (y2 - y1)) / (img_w * img_h)
            center_offset_frac = abs(((x1 + x2) / 2) - img_w / 2) / img_w

            risk_level = classify_collision_risk(area_frac, center_offset_frac)
            overall_level = max(overall_level, risk_level)
            risk_info = RISK_LEVELS[risk_level]

            draw.rectangle([x1, y1, x2, y2], outline=risk_info["color"], width=4)
            draw.text((x1 + 2, max(0, y1 - 14)), f"{cls_name} {conf:.0%}", fill=risk_info["color"])

            detections.append({
                "class": cls_name, "confidence": round(conf, 2),
                "risk_level": risk_level, "risk_label": risk_info["label"],
            })

        detections.sort(key=lambda d: d["risk_level"], reverse=True)
        return annotated, detections, RISK_LEVELS[overall_level]["label"]
    except Exception:
        return None, [], None


def extract_video_frames(video_bytes: bytes, max_frames: int = 6) -> List[Image.Image]:
    """Samples up to `max_frames` evenly-spaced frames from an uploaded video
    for still-frame CV/VLM analysis -- this app never processes a live video
    stream, just a fixed set of decoded frames pulled out of the uploaded
    clip. Returns [] (rather than raising) if `opencv-python` isn't
    installed or the video can't be decoded, so the tab can degrade
    gracefully instead of crashing."""
    try:
        import cv2
    except ImportError:
        return []

    import tempfile
    tmp_path = None
    try:
        with tempfile.NamedTemporaryFile(delete=False, suffix=".mp4") as tmp:
            tmp.write(video_bytes)
            tmp_path = tmp.name

        cap = cv2.VideoCapture(tmp_path)
        total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0)
        if total_frames <= 0:
            cap.release()
            return []

        n = max(1, min(max_frames, total_frames))
        indices = sorted(set(int(i * total_frames / n) for i in range(n)))
        frames = []
        for idx in indices:
            cap.set(cv2.CAP_PROP_POS_FRAMES, idx)
            ok, bgr = cap.read()
            if not ok:
                continue
            rgb = cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB)
            frames.append(Image.fromarray(rgb))
        cap.release()
        return frames
    except Exception:
        return []
    finally:
        if tmp_path and os.path.exists(tmp_path):
            try:
                os.remove(tmp_path)
            except OSError:
                pass


