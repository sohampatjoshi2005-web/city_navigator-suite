            safety_score = round(100 * (1 - avg_safety_risk / max(darkness, 0.01)) * (1 - darkness * 0.5))
            safety_score = max(0, min(100, safety_score))

            m1, m2 = st.columns(2)
            m1.metric("🧘 Sensory-friendliness score", f"{quiet_score}/100",
                      help="Higher = quieter, lower sensory load (simulated).")
            m2.metric("🌙 Night-safety score", f"{safety_score}/100",
                      help=f"For {hour5}:00 -- lower at night, simulated from time-of-day only.")

            tab5_view = st.radio("Show overlay", ["Sensory load", "Night safety"], horizontal=True, key="t5_view")
            layer_data = noise_points if tab5_view == "Sensory load" else safety_points
            heat_layer = pdk.Layer("HeatmapLayer", data=layer_data, get_position=["lng", "lat"],
                                    get_weight="weight", radiusPixels=40)
            mid5 = sampled5[len(sampled5) // 2]
