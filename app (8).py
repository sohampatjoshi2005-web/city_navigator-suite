def find_accessibility_place(lat: float, lng: float) -> Optional[dict]:
    """Find an existing accessibility place bucket within merge distance, if any."""
    for place in st.session_state.accessibility_reports:
        if haversine_km(lat, lng, place["lat"], place["lng"]) <= _ACCESSIBILITY_PLACE_MERGE_KM:
            return place
    return None


def aggregate_accessibility_field(reports: List[dict], field_key: str) -> dict:
    """Majority-vote one field across all reports for a place, with an agreement count."""
    answers = [r["fields"][field_key] for r in reports if r["fields"].get(field_key)]
    if not answers:
        return {"answer": "No data yet", "count": 0, "total": 0, "agreement_pct": 0}
    tally = {}
    for a in answers:
        tally[a] = tally.get(a, 0) + 1
    # Prefer a real answer over "Unknown"/"N/A"-style ones on a tie.
    best = max(tally.items(), key=lambda kv: (kv[1], kv[0] not in _ACCESSIBILITY_UNKNOWN_ANSWERS
                                               and kv[0] != "N/A" and "N/A" not in kv[0]))
    total = len(answers)
    return {"answer": best[0], "count": best[1], "total": total,
            "agreement_pct": round(100 * best[1] / total)}


def accessibility_completeness(reports: List[dict]) -> int:
    """% of fields with a non-Unknown consensus answer -- a simple data-depth score."""
    filled = 0
    for field_key in ACCESSIBILITY_FIELDS:
        agg = aggregate_accessibility_field(reports, field_key)
        if agg["count"] and agg["answer"] not in _ACCESSIBILITY_UNKNOWN_ANSWERS and agg["answer"] != "No data yet" \
                and "N/A" not in agg["answer"]:
            filled += 1
    return round(100 * filled / len(ACCESSIBILITY_FIELDS))

