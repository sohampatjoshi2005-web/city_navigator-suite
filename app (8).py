@st.cache_data(ttl=1800, show_spinner=False)
def fetch_last_yard_access_points(lat: float, lng: float, radius_m: int = LAST_YARD_SEARCH_RADIUS_M) -> list:
    """Finds real, close-by drop-off-relevant features (parking, building
    entrances) around an exact destination point via OpenStreetMap/Overpass
    -- the 'last yard' between where a vehicle can actually stop and the
    precise delivery point, which most consumer routing apps don't surface."""
    overpass_ql = (
        f"[out:json][timeout:20];("
        f'node["amenity"="parking"](around:{radius_m},{lat},{lng});'
        f'node["entrance"](around:{radius_m},{lat},{lng});'
        f'node["building"="entrance"](around:{radius_m},{lat},{lng});'
        f");out center 20;"
    )
    try:
        resp = _session.post(OVERPASS_URL, data={"data": overpass_ql}, headers=REQUEST_HEADERS, timeout=25)
        data = safe_json(resp, "Overpass")
    except Exception:
        return []

    points = []
    for el in data.get("elements", []):
        tags = el.get("tags", {})
        el_lat = el.get("lat") or el.get("center", {}).get("lat")
        el_lng = el.get("lon") or el.get("center", {}).get("lon")
        if el_lat is None or el_lng is None:
            continue
        kind = "🅿️ Parking" if tags.get("amenity") == "parking" else "🚪 Entrance"
        points.append({
            "kind": kind, "name": tags.get("name", kind),
            "lat": el_lat, "lng": el_lng,
            "walk_m": haversine_km(lat, lng, el_lat, el_lng) * 1000,
        })
    points.sort(key=lambda p: p["walk_m"])
    return points


# --- Privacy-Preserving Crowdsourced Traffic --------------------------------
# Reports are stored with coordinates rounded to a coarse grid (~1.1km at
# the equator, adjusted for cell width shrinking with latitude) rather than
# the exact point the person tapped/typed, and carry no name, device, or
# session identifier -- only a category, a coarse cell, and a timestamp.
# This is k-anonymity-style spatial cloaking, not cryptographic privacy, but
# it means individual reports can't be traced back to an exact spot or person.
_TRAFFIC_GRID_DEG = 0.01  # ~1.1 km grid cells


def _round_to_privacy_grid(lat: float, lng: float) -> tuple:
    return (
        round(lat / _TRAFFIC_GRID_DEG) * _TRAFFIC_GRID_DEG,
        round(lng / _TRAFFIC_GRID_DEG) * _TRAFFIC_GRID_DEG,
    )


TRAFFIC_LEVELS = {
    "🟢 Light": 1,
    "🟡 Moderate": 2,
    "🟠 Heavy": 3,
    "🔴 Gridlock": 4,
}


def traffic_reports_near_route(reports: List[dict], route_points: List[List[float]], buffer_m: float = 500) -> List[dict]:
    if not reports or not route_points:
        return []
    sampled = sample_points(route_points, max_samples=60)
    nearby = []
    for r in reports:
        for lat, lng in sampled:
            if haversine_km(r["lat"], r["lng"], lat, lng) * 1000 <= buffer_m:
                nearby.append(r)
                break
    return nearby


