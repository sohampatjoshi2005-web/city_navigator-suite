# TAB 5 -- Sensory & Safety Router
# ============================================================
with tab5:
    st.info(
        "Simulated heuristic overlay on a real route -- illustrates typical noise/crowd "
        "and night-safety patterns using route geometry as a proxy (turns, road density). "
        "Not live noise sensors or crowdsourced safety reports."
    )
    c1, c2 = st.columns(2)
    with c1:
        origin5 = st.text_input("Origin", value="Bhubaneswar, India", key="t5_origin")
    with c2:
        destination5 = st.text_input("Destination", value="Puri, India", key="t5_dest")

    mode_label5 = st.radio("Travel mode", ["Walking", "Cycling"], horizontal=True, key="t5_mode")
    profile5 = {"Walking": "foot-walking", "Cycling": "cycling-regular"}[mode_label5]
    hour5 = st.slider("Hour of day (affects night-safety score)", 0, 23, 20, key="t5_hour")

    if not ORS_KEY:
        st.warning(ORS_KEY_MISSING_MSG)

    if st.button("Score this route", type="primary", key="t5_run") and ORS_KEY:
        try:
            with st.spinner("Fetching real route..."):
                routes5 = fetch_routes([origin5, destination5], profile=profile5, ors_key=ORS_KEY)
            route5 = routes5[0]
            render_international_badge(route5)
            sampled5 = sample_points(route5.polyline_points, max_samples=60)

            # Noise/sensory-load heuristic: deterministic per-point pseudo-random
            # weight (seeded, so re-running with the same route gives the same
            # map) standing in for real ambient-noise/crowd-density data, which
            # no free API exposes at this granularity.
            random.seed(7)
            noise_points = [
                {"lat": lat, "lng": lng, "weight": random.uniform(0.15, 1.0)}
                for lat, lng in sampled5
            ]
            avg_noise = sum(p["weight"] for p in noise_points) / len(noise_points)
            quiet_score = round(100 * (1 - avg_noise))

            # Night-safety heuristic: risk peaks in the small hours, based on
            # hour-of-day alone (no real lighting/foot-traffic data source is
            # free/keyless at this granularity).
            def _darkness_factor(hour: int) -> float:
                diff = min(abs(hour - 2), 24 - abs(hour - 2))
                return max(0.2, 1.0 - diff / 12)

            darkness = _darkness_factor(hour5)
            random.seed(13)
            safety_points = [
                {"lat": lat, "lng": lng, "weight": random.uniform(0.1, 0.9) * darkness}
                for lat, lng in sampled5
            ]
            avg_safety_risk = sum(p["weight"] for p in safety_points) / len(safety_points)
            safety_score = round(100 * (1 - avg_safety_risk / max(darkness, 0.01)) * (1 - darkness * 0.5))
            safety_score = max(0, min(100, safety_score))

            m1, m2 = st.columns(2)
            m1.metric("🧘 Sensory-friendliness score", f"{quiet_score}/100",
                      help="Higher = quieter, lower sensory load (simulated).")
            m2.metric("🌙 Night-safety score", f"{safety_score}/100",
                      help=f"For {hour5}:00 -- lower at night, simulated from time-of-day only.")

            tab5_view = st.radio("Show overlay", ["Sensory load", "Night safety"], horizontal=True, key="t5_view")
            layer_data = noise_points if tab5_view == "Sensory load" else safety_points
            heat_layer = pdk.Layer("HeatmapLayer", data=layer_data, get_position=["lng", "lat"],
                                    get_weight="weight", radiusPixels=40)
            mid5 = sampled5[len(sampled5) // 2]
            st.pydeck_chart(pdk.Deck(map_style="road",
                                      initial_view_state=pdk.ViewState(latitude=mid5[0], longitude=mid5[1], zoom=10),
                                      layers=[heat_layer]))
            st.caption(
                "Darker/hotter areas = higher simulated sensory load or night-safety risk, "
                "depending on the overlay selected above."
            )
        except Exception as e:
            st.error(str(e))

