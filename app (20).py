def weather_route_advice(weather: dict) -> Optional[str]:
    """Plain-language, actionable note based on current conditions -- this is
    the 'micro-routing' signal: it doesn't reroute automatically, but flags
    when exposed/unshaded paths are a bad idea right now."""
    notes = []
    temp = weather.get("temp_c")
    wind = weather.get("wind_kmh")
    precip = weather.get("precip_mm")
    if temp is not None and temp >= 35:
        notes.append(f"🥵 {temp:.0f}°C -- consider a shaded/indoor-adjacent route if walking or cycling.")
    elif temp is not None and temp <= 5:
        notes.append(f"🥶 {temp:.0f}°C -- dress warm; road surfaces may be slippery if near freezing.")
    if wind is not None and wind >= 30:
        notes.append(f"💨 Windy ({wind:.0f} km/h) -- cycling exposed bridges/coastal roads will feel harder.")
    if precip is not None and precip > 0.2:
        notes.append(f"🌧️ Active precipitation ({precip:.1f} mm) -- walking/cycling routes may be slower and less safe.")
    if not notes:
        return None
    return " ".join(notes)


def haversine_m(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    """Straight-line distance in meters between two lat/lng points."""
    R = 6371000.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lng2 - lng1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlambda / 2) ** 2
    return 2 * R * math.asin(math.sqrt(a))


@st.cache_data(ttl=600, show_spinner=False)
def overpass_nearby(lat: float, lng: float, radius_m: int, tag_filters: List[str]) -> list:
    """Nearby OpenStreetMap points matching any of the given tag filters
    (e.g. '"amenity"="toilets"') within radius_m of (lat, lng), via the
    free, keyless Overpass API. Cached for 10 min since POI locations
    don't change quickly and this is a shared public endpoint."""
    clauses = "".join(
        f'node[{f}](around:{radius_m},{lat},{lng});'
        f'way[{f}](around:{radius_m},{lat},{lng});'
        for f in tag_filters
    )
    query = f"[out:json][timeout:20];({clauses});out center 200;"
    resp = _session.post(OVERPASS_URL, data={"data": query}, headers=REQUEST_HEADERS, timeout=25)
    data = safe_json(resp, "Overpass")

    results = []
    for el in data.get("elements", []):
        if el.get("type") == "node":
            plat, plng = el.get("lat"), el.get("lon")
        else:
            center = el.get("center")
            if not center:
                continue
            plat, plng = center["lat"], center["lon"]
        if plat is None or plng is None:
            continue
        tags = el.get("tags", {})
        name = tags.get("name", "Unnamed")
        kind = tags.get("amenity") or tags.get("tourism") or "place"
        results.append({
            "name": name, "lat": plat, "lng": plng, "kind": kind,
            "distance_m": haversine_m(lat, lng, plat, plng),
        })
    results.sort(key=lambda r: r["distance_m"])
    return results


