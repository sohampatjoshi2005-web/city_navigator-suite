class RouteResult:
    """
    Plain class with an explicit __init__ (deliberately NOT a @dataclass).
    Some deployment/build pipelines strip decorators they don't recognize,
    which silently turns a dataclass into a bare class with no generated
    __init__ -- and calling it with keyword arguments then raises
    'RouteResult() takes no arguments'. Writing __init__ by hand avoids
    that failure mode entirely, at the cost of a few extra lines.
    """

    def __init__(
        self,
        summary: str,
        distance_m: float,
        duration_s: float,
        duration_in_traffic_s: Optional[float],
        stop_count: int,
        polyline_points: List[List[float]],
        encoded_polyline: str,
        elevation_profile: Optional[List[float]] = None,
        elevation_gain_m: float = 0.0,
        co2_grams: float = 0.0,
        origin_country: Optional[str] = None,
        destination_country: Optional[str] = None,
    ):
        self.summary = summary
        self.distance_m = distance_m
        self.duration_s = duration_s
        self.duration_in_traffic_s = duration_in_traffic_s
        self.stop_count = stop_count
        self.polyline_points = polyline_points
        self.encoded_polyline = encoded_polyline
        self.elevation_profile = elevation_profile if elevation_profile is not None else []
        self.elevation_gain_m = elevation_gain_m
        self.co2_grams = co2_grams
        self.origin_country = origin_country
        self.destination_country = destination_country

    @property
    def is_international(self) -> bool:
        return bool(
            self.origin_country
            and self.destination_country
            and self.origin_country != self.destination_country
        )


def geocode(place: str) -> tuple:
    """Returns (lat, lng, country_name_or_None)."""
    resp = requests.get(
        NOMINATIM_URL,
        params={"q": place, "format": "json", "limit": 1, "addressdetails": 1},
        headers=REQUEST_HEADERS, timeout=15,
    )
    results = safe_json(resp, "Nominatim geocoding")
    if not results:
        raise RuntimeError(f"Could not geocode '{place}' -- try a more specific place name.")
    result = results[0]
    country = result.get("address", {}).get("country")
    return float(result["lat"]), float(result["lon"]), country


def compute_elevation_gain(profile: List[float]) -> float:
    gain = 0.0
    for prev, curr in zip(profile, profile[1:]):
        if curr - prev > 0:
            gain += curr - prev
    return gain


def circle_polygon(lat: float, lng: float, radius_m: float, n_points: int = 16) -> List[List[float]]:
    """Approximate a circle as a closed polygon ring [[lng, lat], ...] for avoid_polygons."""
    R = 6371000.0
    lat_rad = math.radians(lat)
    ring = []
    for i in range(n_points):
        angle = 2 * math.pi * i / n_points
        dlat = (radius_m * math.cos(angle)) / R
        dlng = (radius_m * math.sin(angle)) / (R * math.cos(lat_rad))
        ring.append([lng + math.degrees(dlng), lat + math.degrees(dlat)])
    ring.append(ring[0])
    return ring


def build_avoid_polygons(hazard_zones: List[dict]) -> Optional[dict]:
    if not hazard_zones:
        return None
    polygons = [[circle_polygon(z["lat"], z["lng"], z["radius_m"])] for z in hazard_zones]
    return {"type": "MultiPolygon", "coordinates": polygons}


def _fetch_single_route(
    coords_lnglat: List[List[float]], profile: str, preference: str,
    avoid_features: List[str], avoid_polygons: Optional[dict], ors_key: str,
) -> Optional[dict]:
    body = {
        "coordinates": coords_lnglat,
        "elevation": True,
        "instructions": True,
        "preference": preference,
    }
    options = {}
    if avoid_features:
        options["avoid_features"] = avoid_features
    if avoid_polygons:
        options["avoid_polygons"] = avoid_polygons
    if options:
        body["options"] = options

    url = ORS_DIRECTIONS_URL_TMPL.format(profile=profile)
    headers = {"Authorization": ors_key, "Content-Type": "application/json"}
    resp = requests.post(url, json=body, headers=headers, timeout=20)
    data = safe_json(resp, "OpenRouteService")
    if resp.status_code != 200:
        msg = data.get("error", {}).get("message", str(data))
        # ORS returns 2010 'routable point not found' / 2004 'unable to find
        # a route between points' when the profile can't bridge the gap --
        # most commonly because it would require crossing an ocean.
        if resp.status_code in (404, 500) and ("route" in msg.lower() or "point" in msg.lower()):
            raise RuntimeError(
                "No route found between these points for the selected travel mode. "
                "This usually means the two locations aren't connected by road/path/cycleway "
                "(e.g. they're on different continents separated by ocean, with no ferry link "
                "in the routing data). Try a route within the same landmass, or pick a "
                "different travel mode."
            )
        raise RuntimeError(f"OpenRouteService error: {msg}")
    features = data.get("features", [])
    return features[0] if features else None


def fetch_routes(
    waypoint_addresses: List[str], profile: str = "driving-car",
    avoid_features: Optional[List[str]] = None,
    hazard_zones: Optional[List[dict]] = None,
    ors_key: str = "",
) -> List[RouteResult]:
    avoid_features = avoid_features or []
    avoid_polygons = build_avoid_polygons(hazard_zones or [])

    coords_lnglat = []
    countries = []
    for addr in waypoint_addresses:
        lat, lng, country = geocode(addr)
        coords_lnglat.append([lng, lat])
        countries.append(country)

    origin_country = countries[0]
    destination_country = countries[-1]

    preferences = [("recommended", "Recommended route"), ("shortest", "Shortest route")]
    results = []
    seen_distances = set()
    for preference, label in preferences:
        feature = _fetch_single_route(coords_lnglat, profile, preference, avoid_features, avoid_polygons, ors_key)
        if feature is None:
            continue
        props = feature["properties"]
        summary = props.get("summary", {})
        distance_m = summary.get("distance", 0.0)

        rounded = round(distance_m, -2)
        if rounded in seen_distances:
            continue
        seen_distances.add(rounded)

        duration_s = summary.get("duration", 0.0)
        stop_count = 0
        for segment in props.get("segments", []):
            for step in segment.get("steps", []):
                if step.get("type") in STOP_LIKE_MANEUVER_TYPES:
                    stop_count += 1

        coords = feature["geometry"]["coordinates"]
        points = [[c[1], c[0]] for c in coords]
        elevation_profile = [c[2] for c in coords if len(c) > 2]
        encoded = polyline.encode([(lat, lng) for lat, lng in points])

        r = RouteResult(
            summary=label, distance_m=distance_m, duration_s=duration_s,
            duration_in_traffic_s=None, stop_count=stop_count,
            polyline_points=points, encoded_polyline=encoded,
            elevation_profile=elevation_profile,
            origin_country=origin_country, destination_country=destination_country,
        )
        r.elevation_gain_m = compute_elevation_gain(elevation_profile)
        results.append(r)

    if not results:
        raise RuntimeError("No routes returned -- try different locations or fewer restrictions.")
    return results


def sample_points(points: List[List[float]], max_samples: int = 100) -> List[List[float]]:
    if len(points) <= max_samples:
        return points
    step = len(points) / max_samples
    return [points[int(i * step)] for i in range(max_samples)]


def render_international_badge(route: RouteResult):
    if route.is_international:
        st.info(f"🌍 International route: **{route.origin_country} → {route.destination_country}**")


